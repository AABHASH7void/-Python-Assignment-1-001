x = "50"
y = 7.8
z = 15

print("int(x)   :", int(x))      # string to integer
print("int(y)   :", int(y))      # float to integer
print("float(z) :", float(z))    # integer to float
print("float(x) :", float(x))    # string to float
print("str(z)   :", str(z))      # integer to string
print("str(y)   :", str(y))      # float to string